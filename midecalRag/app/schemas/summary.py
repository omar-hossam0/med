"""Schemas for the patient-summary endpoint (owner addition, 2026-11-23).

This endpoint is **not** part of the frozen Section 5 contract, so it lives in
its own module: adding it here keeps ``app/schemas/contract.py`` untouched and
makes the extension explicit.

Response shape::

    {
      "status": "ok" | "no_records" | "verification_failed",
      "message": "<localized status message>",
      "sections": [{"key", "title", "content", "sources": [...]}],
      "sources": [{"document_id", "doc_type", "doc_date", "reference_snippet"}]
    }

``message`` is generated by code, never by the LLM, so it cannot hallucinate.
Every ``Source`` is built from a retrieved parent (same rule as Phase 6).
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.contract import OptionalFilters, Source

SummaryStatus = Literal["ok", "no_records", "verification_failed"]
SummarySectionKey = Literal["medications", "labs", "reports", "visits"]
Language = Literal["ar", "en"]


class SummarySection(BaseModel):
    model_config = ConfigDict(extra="ignore")

    key: SummarySectionKey
    title: str  # localized heading shown to the doctor
    content: str  # citation markers already stripped
    sources: list[Source] = Field(default_factory=list)


class PatientSummaryRequest(BaseModel):
    model_config = ConfigDict(extra="ignore")

    patient_id: str = Field(min_length=1, max_length=128)
    # Optional: the brief has no question to infer the language from.
    language: Language | None = None
    optional_filters: OptionalFilters = Field(default_factory=OptionalFilters)
    # Optional per-request cap on how many documents feed the brief.
    max_documents: int | None = Field(default=None, ge=1, le=50)


class PatientSummaryResponse(BaseModel):
    model_config = ConfigDict(extra="ignore")

    status: SummaryStatus
    message: str
    sections: list[SummarySection] = Field(default_factory=list)
    sources: list[Source] = Field(default_factory=list)
